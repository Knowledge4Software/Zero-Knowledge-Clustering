import json
from pathlib import Path

import pytest

from commitjl.hashing import mimc_hash, mimc_hash_bytes, mimc_round_constants, sha256, shake256, BN254_FR

GOLDEN_PATH = Path(__file__).parent / "golden" / "mimc.json"


def test_mimc_hash_deterministic():
    h1 = mimc_hash([1, 2, 3])
    h2 = mimc_hash([1, 2, 3])
    assert h1 == h2


def test_mimc_hash_avalanche_like():
    h1 = mimc_hash([1, 2, 3])
    h2 = mimc_hash([1, 2, 4])
    assert h1 != h2


def test_mimc_hash_bytes_deterministic():
    a = mimc_hash_bytes(b"hello world")
    b = mimc_hash_bytes(b"hello world")
    assert a == b
    assert 0 <= a < BN254_FR


def test_sha256_shake256_basic():
    assert sha256(b"x") == sha256(b"x")
    assert len(shake256(b"seed", 64)) == 64


@pytest.mark.skipif(not GOLDEN_PATH.exists(), reason="golden vectors not generated (run `go run ./zk/cmd/golden`)")
def test_mimc_round_constants_match_golden_vectors():
    golden = json.loads(GOLDEN_PATH.read_text())
    expected = [int(c) for c in golden["round_constants"]]
    assert mimc_round_constants() == expected


@pytest.mark.skipif(not GOLDEN_PATH.exists(), reason="golden vectors not generated (run `go run ./zk/cmd/golden`)")
def test_mimc_matches_gnark_crypto_golden_vectors():
    """Byte-exact cross-check against ecc/bn254/fr/mimc in gnark-crypto (Go),
    using vectors generated by code/zk/cmd/golden and stored at
    tests/golden/mimc.json. Covers single-element hashes, multi-element
    sequences, and commit.py-style leaf/node hashes."""
    golden = json.loads(GOLDEN_PATH.read_text())

    for s, expected in golden["single"].items():
        assert mimc_hash([int(s)]) == int(expected), f"single({s})"

    for case in golden["sequences"]:
        inputs = [int(x) for x in case["inputs"]]
        assert mimc_hash(inputs) == int(case["digest"]), f"sequence({inputs})"

    for case in golden["leaf_hash"]:
        assert mimc_hash([int(case["value"]), int(case["salt"])]) == int(case["digest"])

    for case in golden["node_hash"]:
        assert mimc_hash([int(case["left"]), int(case["right"])]) == int(case["digest"])

    for case in golden["bytes_hash"]:
        data = bytes.fromhex(case["hex"])
        assert mimc_hash_bytes(data) == int(case["digest"]), f"bytes({case['hex']})"


@pytest.mark.skipif(not GOLDEN_PATH.exists(), reason="golden vectors not generated (run `go run ./zk/cmd/golden`)")
def test_merkle_commit_matches_golden_vector():
    """Cross-check commit.py's Merkle construction (leaf/node hashing,
    signed-to-field encoding) against the Go-computed root for the same
    small 2x2 matrix."""
    import numpy as np

    from commitjl.commit import commit_matrix

    golden = json.loads(GOLDEN_PATH.read_text())
    case = golden["merkle_example"]
    X = np.array(case["X_flat"], dtype=np.int64).reshape(2, 2)
    salt = int(case["salt"])
    commitment = commit_matrix(X, salt=salt)
    assert [str(v) for v in commitment.leaves] == case["leaves"]
    assert str(commitment.root) == case["root"]

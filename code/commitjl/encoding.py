"""Canonical little-endian byte encodings for protocol objects.

Manuscript reference: Alg. 1 step 2-4, "The byte encoding fixes the XOF,
domain tags, word width, rejection rule, column order, sign-bit order, and
sparse-list serialization." (Sec. "Sparse matrix generation").

All integers are encoded little-endian, fixed width, so that Python and a
future Go/gnark host implementation can be made byte-identical. Every encoded
blob is prefixed with the protocol version tag so that transcripts cannot be
replayed across incompatible versions.
"""
from __future__ import annotations

import struct
from dataclasses import dataclass
from typing import Iterable, List, Sequence, Tuple

import numpy as np

VERSION_TAG = b"CommitJL-v1"

U8 = "little-endian uint8"


def _u32(x: int) -> bytes:
    return struct.pack("<I", x & 0xFFFFFFFF)


def _u64(x: int) -> bytes:
    return struct.pack("<Q", x & 0xFFFFFFFFFFFFFFFF)


def _i64(x: int) -> bytes:
    # two's complement signed 64-bit, little-endian
    return struct.pack("<q", x)


def encode_version() -> bytes:
    return VERSION_TAG


def encode_matrix_X(X: np.ndarray, scale: int) -> bytes:
    """Canonical encoding of the private quantized dataset X (n,d integers).

    Layout: version tag || n(u32) || d(u32) || scale(u32) || row-major i64 entries.
    """
    X = np.asarray(X)
    assert X.ndim == 2
    n, d = X.shape
    out = bytearray()
    out += VERSION_TAG
    out += _u32(n)
    out += _u32(d)
    out += _u32(scale)
    flat = X.astype(np.int64).ravel(order="C")
    out += flat.tobytes()  # numpy int64 is little-endian on all supported platforms
    return bytes(out)


def encode_theta(centroids: np.ndarray, m: int, q: int, mu: bytes = b"") -> bytes:
    """Encode public parameters theta = (C, m, q, mu)."""
    C = np.asarray(centroids)
    assert C.ndim == 2
    k, d = C.shape
    out = bytearray()
    out += VERSION_TAG
    out += b"THETA"
    out += _u32(k)
    out += _u32(d)
    out += _u32(m)
    out += _u32(q)
    out += _u32(len(mu))
    out += mu
    out += C.astype(np.int64).ravel(order="C").tobytes()
    return bytes(out)


@dataclass(frozen=True)
class SparseRecord:
    t: int      # input coordinate (column of A^T view / column t in [d])
    ell: int    # slot index in [q]
    row: int    # output row r in [m]
    sign: int   # +1 or -1


def encode_sparse_list(records: Sequence[SparseRecord]) -> bytes:
    """Column-major canonical encoding of the sparse list: records (t, ell, row, sign).

    Ordered by (t asc, ell asc) as generated by the column-wise XOF expansion.
    """
    out = bytearray()
    out += VERSION_TAG
    out += b"SPARSEA"
    out += _u32(len(records))
    for r in records:
        out += _u32(r.t)
        out += _u32(r.ell)
        out += _u32(r.row)
        sign_bit = 0 if r.sign == 1 else 1
        out += bytes([sign_bit])
    return bytes(out)


def sparse_list_to_dense(records: Sequence[SparseRecord], m: int, d: int) -> np.ndarray:
    A = np.zeros((m, d), dtype=np.int64)
    for r in records:
        A[r.row, r.t] = r.sign
    return A


def dense_to_sparse_list(A: np.ndarray) -> List[SparseRecord]:
    """Recover canonical-ish sparse list from a dense {-1,0,1} matrix (column order, row order)."""
    m, d = A.shape
    records: List[SparseRecord] = []
    for t in range(d):
        col = A[:, t]
        rows = np.nonzero(col)[0]
        for ell, row in enumerate(rows):
            records.append(SparseRecord(t=t, ell=ell, row=int(row), sign=int(col[row])))
    return records


def signed_to_field(x: int, p: int) -> int:
    """Canonical signed -> field mapping: negative x -> p + x."""
    x = int(x)
    if x < 0:
        return p + x
    return x


def field_to_signed(v: int, p: int, bound: int) -> int:
    """Inverse of signed_to_field for values known to lie in [-bound, bound]."""
    v = int(v) % p
    if v > p // 2:
        return v - p
    return v

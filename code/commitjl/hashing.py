"""Hash primitives used by the protocol.

- MiMC-BN254 (Miyaguchi-Preneel construction), byte-exact with gnark-crypto's
  `ecc/bn254/fr/mimc` package (verified against golden vectors generated by
  the Go implementation itself; see code/zk/cmd/golden and
  tests/test_hashing.py::test_mimc_matches_golden_vectors).

  Exact algorithm (transcribed from gnark-crypto v0.21.0 mimc.go):

  Round-constant derivation (`initConstants`):
      r0 = Keccak256(b"seed")                  # note: *Keccak-256*, i.e.
                                                  # the pre-NIST-padding
                                                  # variant (golang.org/x/
                                                  # crypto/sha3's
                                                  # NewLegacyKeccak256), NOT
                                                  # SHA3-256 (FIPS 202).
      for i in range(110):
          r_{i+1} = Keccak256(r_i)
          c_i = int_from_bytes_be(r_{i+1}) mod p
      (so c_i = Keccak256^{i+2}(b"seed") mod p; there is no leading c_0 = 0 --
      that was a P1/P2 approximation and is wrong.)

  Block cipher (`encrypt`, message m, key k = current running state h):
      x = m
      for c in constants:
          x = (x + k + c) mod p
          x = x^5 mod p
      return (x + k) mod p

  Compression (Miyaguchi-Preneel, `checksum`), h_0 = 0:
      for m in inputs:
          r = encrypt(m, key=h)
          h = (r + h + m) mod p          # note the extra "+ m" feed-forward
                                            # term that the P1/P2 version
                                            # omitted.
      return h

- SHA-256 / SHAKE256 host-side wrappers (thin hashlib wrappers), used for the
  seed derivation s = H("CommitJL-v1" || C_X || C_theta || rho) and for the
  sparse-matrix generator's XOF.
"""
from __future__ import annotations

import hashlib
from functools import lru_cache
from typing import List, Sequence

from Crypto.Hash import keccak

# BN254 (a.k.a. alt_bn128) scalar field modulus (Fr), used by gnark-crypto's
# ecc/bn254/fr package.
BN254_FR = 21888242871839275222246405745257275088548364400416034343698204186575808495617

MIMC_SEED = b"seed"
MIMC_ROUNDS = 110
MIMC_EXPONENT = 5


def keccak256(data: bytes) -> bytes:
    """Original (pre-NIST-padding) Keccak-256, matching golang.org/x/crypto/
    sha3's NewLegacyKeccak256 and gnark-crypto's constant derivation. This is
    NOT the same as hashlib.sha3_256 (FIPS 202 uses different padding)."""
    return keccak.new(data=data, digest_bits=256).digest()


@lru_cache(maxsize=1)
def mimc_round_constants(n_rounds: int = MIMC_ROUNDS, p: int = BN254_FR) -> List[int]:
    """Derive round constants byte-exact with gnark-crypto's initConstants():

    r0 = Keccak256(seed); r_{i+1} = Keccak256(r_i); c_i = int_be(r_{i+1}) mod p.
    """
    constants = []
    r = keccak256(MIMC_SEED)
    for _ in range(n_rounds):
        r = keccak256(r)
        constants.append(int.from_bytes(r, "big") % p)
    return constants


def _mimc_encrypt(msg: int, key: int, p: int = BN254_FR) -> int:
    """MiMC block cipher encryption of `msg` under `key` in F_p."""
    x = msg % p
    rcs = mimc_round_constants(MIMC_ROUNDS, p)
    for c in rcs:
        x = (x + key + c) % p
        x = pow(x, MIMC_EXPONENT, p)
    return (x + key) % p


def mimc_hash(inputs: Sequence[int], p: int = BN254_FR) -> int:
    """Miyaguchi-Preneel sponge/compression hash over a sequence of field elements.

    h_0 = 0; h_i = MiMC_Enc(m_i, h_{i-1}) + h_{i-1} + m_i  (mod p)
    Returns the final digest state h_n. Byte-exact with gnark-crypto.
    """
    h = 0
    for m in inputs:
        m = int(m) % p
        e = _mimc_encrypt(m, h, p)
        h = (e + h + m) % p
    return h


def mimc_hash_bytes(data: bytes, p: int = BN254_FR) -> int:
    """Convenience: chunk raw bytes into 31-byte (248-bit, safely < p) field
    elements, big-endian within each chunk, and MiMC-hash the sequence."""
    chunk_size = 31
    elems = []
    for i in range(0, len(data), chunk_size):
        chunk = data[i:i + chunk_size]
        elems.append(int.from_bytes(chunk, "big") % p)
    if not elems:
        elems = [0]
    return mimc_hash(elems, p)


def sha256(data: bytes) -> bytes:
    return hashlib.sha256(data).digest()


def shake256(data: bytes, out_len: int) -> bytes:
    return hashlib.shake_256(data).digest(out_len)


def shake256_stream(data: bytes):
    """Generator yielding successive 4-byte (32-bit) little-endian words from
    a SHAKE256 XOF seeded with `data`. Used by sparse_gen.py's rejection
    sampling loop, which needs a variable, unbounded number of words.

    hashlib.digest(n) returns a prefix, rather than advancing the XOF. Start
    with a short prefix for sparse columns and grow the refill size up to the
    previous 4096-byte block. Refill boundaries never change the word stream.
    """
    shake = hashlib.shake_256(data)
    block = 64
    pos = 0
    while True:
        buf = shake.digest(pos + block)
        while pos + 4 <= len(buf):
            yield buf[pos:pos + 4]
            pos += 4
        block = min(2 * block, 4096)
